#!/usr/bin/env python3
"""Keep the offline prototype's screen styles and icons in sync with production."""

import argparse
from pathlib import Path
import re
import textwrap


ROOT = Path(__file__).resolve().parents[1]
STYLE = re.compile(r"<style>(.*?)</style>", re.DOTALL)
ICONS = re.compile(r"^[ \t]*const icons\s*=\s*\{.*?\};(?=\s*\n[ \t]*const icon\s*=)",
                   re.MULTILINE | re.DOTALL)
ICON_RENDERER = re.compile(r"^[ \t]*const icon\s*=\s*[^\n]+;$", re.MULTILINE)


def unique_match(pattern, source, name):
    matches = list(pattern.finditer(source))
    if len(matches) != 1:
        raise ValueError(f"{name}必须且只能出现一次")
    return matches[0]


def render_prototype(root=ROOT):
    """Replace presentation copies only; preserve the prototype's offline actions."""
    root = Path(root)
    target = root / 'docs/prototypes/r1-small-screen.html'
    prototype = target.read_text(encoding='utf-8')
    css = (root / 'ui/assets/panel.css').read_text(encoding='utf-8').rstrip()
    shell = (root / 'docs/prototypes/shell.css').read_text(encoding='utf-8').rstrip()
    production = (root / 'ui/assets/panel.js').read_text(encoding='utf-8')
    icons = textwrap.indent(textwrap.dedent(unique_match(ICONS, production, '正式小屏图标定义').group()), '    ')
    renderer = textwrap.indent(textwrap.dedent(unique_match(ICON_RENDERER, production, '正式小屏图标渲染').group()), '    ')
    styles = list(STYLE.finditer(prototype))
    if not styles:
        raise ValueError('缺少原型样式块')
    unique_match(ICONS, prototype, '原型图标定义')
    unique_match(ICON_RENDERER, prototype, '原型图标渲染')
    generated = ('<style>\n/* Generated by scripts/build-prototype.py from ui/assets/panel.css. */\n'
                 + css + '\n\n/* Prototype canvas only; screen components stay identical. */\n'
                 + shell + '\n  </style>')
    # Older prototypes contain several successive copies of component CSS.
    # Consolidate all of them into one production block plus the canvas shell.
    rendered = STYLE.sub(lambda match: generated if match.start() == styles[0].start() else '', prototype)
    rendered = ICONS.sub(lambda _: icons, rendered, count=1)
    rendered = ICON_RENDERER.sub(lambda _: renderer, rendered, count=1)
    return re.sub(r"(?m)^[ \t]+$", '', rendered)


def sync_prototype(root=ROOT, *, check=False):
    """Check mode detects stale copies without modifying the standalone artifact."""
    target = Path(root) / 'docs/prototypes/r1-small-screen.html'
    rendered = render_prototype(root)
    changed = rendered != target.read_text(encoding='utf-8')
    if changed and check:
        raise ValueError('原型图标或样式尚未同步，请运行 python scripts/build-prototype.py')
    if changed:
        target.write_text(rendered, encoding='utf-8', newline='\n')
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='只检查同步状态，不改写原型')
    args = parser.parse_args()
    try:
        changed = sync_prototype(check=args.check)
    except (OSError, ValueError) as error:
        parser.exit(1, f'原型同步失败：{error}\n')
    print('Prototype synchronized' if changed else 'Prototype is up to date')


if __name__ == '__main__':
    main()
